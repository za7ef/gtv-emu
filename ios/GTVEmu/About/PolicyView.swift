                        Text(item.element.0).font(.headline)
                        Text(item.element.1).font(.body)
                    }
                }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
            .padding()
        }
        .navigationTitle(policy.title)
        .navigationBarTitleDisplayMode(.inline)
    }
}
