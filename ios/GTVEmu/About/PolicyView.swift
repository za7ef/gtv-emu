            ]
        case .privacy:
            return [
                ("ملخص", "لا يجمع التطبيق أي بيانات شخصية، ولا يحتوي على حسابات أو إعلانات أو أدوات تحليل أو تتبّع."),
                ("البيانات على الجهاز", "تُحفظ ملفات الأنظمة والإعدادات وسجلّ الطرفية على الجهاز فقط، داخل مجلد التطبيق، ولا تُرسل إلى أي جهة. يمكن حذفها في أي وقت بحذف التطبيق أو من تطبيق الملفات."),
                ("الاتصالات الشبكية", "يتصل التطبيق بخدمة GitHub فقط لغرضين: تنزيل قائمة ملفات الأنظمة وملفاتها، والتحقق من وجود إصدار أحدث من التطبيق. تخضع هذه الاتصالات لسياسة خصوصية GitHub، ولا يُرسل التطبيق فيها أي معلومات عن المستخدم."),
                ("رمز الوصول", "إذا أُدخل رمز وصول GitHub في الإعدادات، يُحفظ على الجهاز فقط ويُستخدم في طلبات تنزيل الملفات من GitHub دون غيرها."),
                ("الشبكة داخل الأنظمة الافتراضية", "الأنظمة التي تعمل داخل المحاكي يمكنها الاتصال بالإنترنت عبر شبكة داخلية. ما تفعله هذه الأنظمة خاضع لها ولسياساتها، وليس للتطبيق."),
