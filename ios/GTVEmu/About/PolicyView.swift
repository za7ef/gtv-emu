struct PolicyView: View {
    let policy: Policy

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 18) {
                Text(policy.updated).font(.footnote).foregroundStyle(.secondary)
                ForEach(Array(policy.sections.enumerated()), id: \.offset) { item in
                    VStack(alignment: .leading, spacing: 6) {
                        Text(item.element.0).font(.headline)
                        Text(item.element.1).font(.body)
                    }
                }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
            .padding()
        }
        .navigationTitle(policy.title)
        .navigationBarTitleDisplayMode(.inline)
    }
}
