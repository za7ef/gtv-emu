    var title: String {
        switch self {
        case .terms: return "سياسة الاستخدام"
        case .privacy: return "سياسة الخصوصية"
        }
    }

    var updated: String { "آخر تحديث: 21 نوفمبر 2026" }

    var sections: [(String, String)] {
        switch self {
        case .terms:
            return [
                ("التعريف", "GTV Emu تطبيق مجاني ومفتوح المصدر يحاكي معالجًا بمعمارية AArch64 لتشغيل أنظمة لينكس وأندرويد على أجهزة آيفون وآيباد. يُقدَّم التطبيق لأغراض التجربة والتعلّم."),
                ("ملفات الأنظمة", "لا يتضمن التطبيق أي نظام تشغيل. تُنزَّل ملفات الأنظمة من إصدارات المستودع أو تُستورد من تطبيق الملفات، ويتحمّل المستخدم مسؤولية التأكد من حقه في استخدام أي ملف يُشغّله، والالتزام بتراخيصه."),
                ("الاستخدام المقبول", "يُمنع استخدام التطبيق في أي نشاط مخالف للأنظمة والقوانين المعمول بها، ومن ذلك تشغيل محتوى منسوخ بطريقة غير مشروعة أو تجاوز أنظمة حماية المحتوى."),
                ("التثبيت والمترجم الفوري", "يُثبَّت التطبيق خارج متجر التطبيقات بأدوات التثبيت الجانبي، ويعتمد تفعيل المترجم الفوري على أدوات خارجية مثل StikDebug. لا يتحكم التطبيق في هذه الأدوات ولا يضمن عملها على كل إصدارات iOS."),
                ("إخلاء المسؤولية", "يُقدَّم التطبيق «كما هو» دون أي ضمان. التطبيق في مرحلة تجريبية، وقد يتوقف أو يستهلك قدرًا كبيرًا من الذاكرة والبطارية، ولا يتحمّل المطوّر أي ضرر ينتج عن استخدامه، بما في ذلك فقدان البيانات داخل الأنظمة الافتراضية."),
